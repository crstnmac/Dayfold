// Generates the macOS menu-bar template icon (black + alpha only) at 1x and 2x: a sun rising
// over a fold.
// Writes resources/trayTemplate{,@2x}.png and src/main/tray-icon-data.ts (embedded base64, so
// packaging needs no extra resource copying). Run: node scripts/make-tray-icon.mjs
import { deflateSync } from 'node:zlib'
import { writeFileSync } from 'node:fs'

const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})
const crc = (buf) => {
  let c = 0xffffffff
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
const chunk = (type, data) => {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type), data])
  const c = Buffer.alloc(4)
  c.writeUInt32BE(crc(body))
  return Buffer.concat([len, body, c])
}
const png = (size, alpha) => {
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(size, 0)
  ihdr.writeUInt32BE(size, 4)
  ihdr[8] = 8
  ihdr[9] = 6 // RGBA
  const raw = Buffer.alloc(size * (size * 4 + 1))
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0
    for (let x = 0; x < size; x++) {
      const o = y * (size * 4 + 1) + 1 + x * 4
      raw[o + 3] = alpha[y * size + x]
    }
  }
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0))
  ])
}

// Geometry on a 16-unit grid (y points down): a sun rising out of an open fold, matching the app
// icon. The sun's lower half is hidden behind the fold and a hairline of space separates them.
const distSeg = (px, py, ax, ay, bx, by) => {
  const dx = bx - ax
  const dy = by - ay
  const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
  return Math.hypot(px - (ax + t * dx), py - (ay + t * dy))
}
const SUN = { x: 8, y: 7.6, r: 3.6 }
const RAY_ANGLES = [18, 54, 90, 126, 162]
const foldTop = (x) => 10.7 - (Math.abs(x - 8) / 6.5) * 1.9 // valley: lowest at the centre
const foldBottom = (x) => 15 - (Math.abs(x - 8) / 6.5) * 1.9
const covered = (x, y) => {
  // the two folded panels, with a gap at the crease
  if (x >= 1.5 && x <= 14.5 && Math.abs(x - 8) >= 0.4 && y >= foldTop(x) && y <= foldBottom(x))
    return 1
  // the sun, only above the fold with a gap
  if (Math.hypot(x - SUN.x, y - SUN.y) <= SUN.r && y <= foldTop(x) - 1) return 1
  for (const deg of RAY_ANGLES) {
    const a = (deg * Math.PI) / 180
    const c = Math.cos(a)
    const sn = Math.sin(a)
    if (distSeg(x, y, SUN.x + c * 5.1, SUN.y - sn * 5.1, SUN.x + c * 6.6, SUN.y - sn * 6.6) <= 0.55)
      return 1
  }
  return 0
}
const render = (size) => {
  const ss = 8
  const scale = 16 / size
  const out = new Uint8Array(size * size)
  for (let y = 0; y < size; y++)
    for (let x = 0; x < size; x++) {
      let sum = 0
      for (let j = 0; j < ss; j++)
        for (let i = 0; i < ss; i++)
          sum += covered((x + (i + 0.5) / ss) * scale, (y + (j + 0.5) / ss) * scale)
      out[y * size + x] = Math.round((sum / (ss * ss)) * 255)
    }
  return out
}

const p1 = png(16, render(16))
const p2 = png(32, render(32))
writeFileSync('resources/trayTemplate.png', p1)
writeFileSync('resources/trayTemplate@2x.png', p2)
writeFileSync(
  'src/main/tray-icon-data.ts',
  `// Generated by scripts/make-tray-icon.mjs. Black + alpha template image (1x and 2x).\nexport const TRAY_ICON_1X = '${p1.toString('base64')}'\nexport const TRAY_ICON_2X = '${p2.toString('base64')}'\n`
)
console.log('wrote tray icons', p1.length, p2.length)
